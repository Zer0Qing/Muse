package io.zer0.muse.runtime

/**
 * 子进程/运行时的**失败分类**（DSHGO 阶段 1 的最小状态机）。
 *
 * ## 为什么要有它
 * Muse 现在有五条"起一个子进程跑东西"的路径（内置 Node、内置 Python、JS 沙盒、
 * MCP stdio 服务、终端会话），但它们把三种完全不同的事情报成同一句话：
 * **环境根本起不来**、**跑着跑着被系统结束**、**插件自己写挂了**。
 * 用户和模型拿到的是同一个 `exit=1`，于是不知道该重试、该去装运行时、还是该改插件。
 *
 * 本文件只做**判定**，不做任何重启/重试动作：哪些失败可以自动重试、预算多少，
 * 由各条路径自己决定（MCP 已有自己的重连预算；插件常驻服务是刻意**不**自动复活的，
 * 见 `PluginServiceHost` 的注释）。分类器的 `autoRetry` 只是"这类失败值不值得重试"的**建议值**，
 * 不是许可 —— 把它当许可用就是绕过宿主策略。
 *
 * ## 与参考实现的差别（避免照搬）
 * 参考项目要管一个 PRoot 里的常驻引擎，所以它有"运行代次 + 有限重启 + 安全模式"整套；
 * Muse 的这几条路径里只有 MCP 是真正常驻，其余都是**一次性 exec**。
 * 因此这里只取三条能落地不空转的原则：
 *  1. 「没跑起来」和「跑起来之后死」必须是不同的类别（重试价值完全不同）；
 *  2. **用户主动停**永不算失败（否则任何计数型策略都会被用户的正常操作污染）；
 *  3. 磁盘满单独成类（重试只会继续写坏，必须先让人清理）。
 */
enum class ProcessFailureKind(
    /** 一句话人话原因，直接进用户/模型可见的文案。 */
    val summary: String,
    /** 这类失败**值不值得**自动重试（见类注释：这是建议值，不是许可）。 */
    val autoRetry: Boolean,
) {
    /** 用户点了停止/主动关闭：不是故障，绝不该被计入任何失败计数。 */
    USER_STOPPED("已由用户主动停止", false),

    /** 从没进入就绪状态就退出：命令不存在、依赖缺失、二进制不可执行、权限被拒。 */
    NEVER_STARTED("运行时未能启动（命令不存在、依赖缺失或不可执行）", false),

    /** 输出里出现磁盘满特征：重试只会继续写坏，必须先清理。 */
    NO_SPACE("设备存储空间不足", false),

    /** 超出预算时间被我们主动终止。 */
    TIMED_OUT("执行超时，子进程已终止", true),

    /** 就绪后很快就死：更像是这次启动本身有问题（配置/补丁/依赖版本）。 */
    CRASHED_EARLY("启动后很快退出", true),

    /** 跑了一段之后死：多半是这次任务本身或系统回收，值得重试一次。 */
    CRASHED_LATE("运行中退出（可能被系统回收或任务本身出错）", true),

    /** 正常退出但**没有**交出结果（协议/输出问题），与崩溃要分开。 */
    NO_RESULT("进程正常结束但没有产出结果", false),
}
