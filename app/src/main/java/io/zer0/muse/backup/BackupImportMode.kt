package io.zer0.muse.backup

/**
 * 备份导入的两种语义，由用户在导入确认弹窗里显式选择。
 *
 * - [OVERWRITE]：用备份替换本机全部数据。恢复期间先落保护副本，
 *   三库（MuseDb / MemoryDb / FactDb）、设置快照、文件型存储一并替换。
 *   这是历史行为，保持逐字节不变以免影响已验收的恢复链路。
 * - [MERGE]：只把备份里的**对话记录**并入本机，不动助手、技能、知识库、
 *   自动化、设置与记忆。每条会话与消息都换新 id，因此同一份备份导两次
 *   会得到两份副本，而不是互相覆盖。
 *
 * 为什么合并只带对话：其余表要么是全局配置（助手 / 技能 / 供应商），
 * 要么是派生物（记忆摘要、事实、看板），合并进来只会让两套配置互相打架。
 * 用户要"再补一点历史进来"时，需要的正是对话本身。
 */
enum class BackupImportMode {
    OVERWRITE,
    MERGE,
}
