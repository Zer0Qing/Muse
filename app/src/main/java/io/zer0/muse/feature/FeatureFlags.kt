package io.zer0.muse.feature

/**
 * v2.6.7: 功能开关 —— 未成熟功能的统一显隐闸门。
 *
 * 为什么用编译期常量而不是运行时设置：
 *  - 运行时开关（如 `miniPhoneEnabledFlow`）对用户可见、可绕过，隐藏不彻底；
 *  - 编译期常量能让 R8 把不可达分支裁掉，产物里连入口代码都不剩；
 *  - "之后再加回来"只需把常量改回 true，**代码一行不删**。
 *
 * 约定（v2.6.22 起按实际设计写清，原来的说法与代码相反）：
 *  - **入口**过 [MINI_PHONE_ENTRY] 与设置项 `browseVisible`：首页与设置分类页不露；
 *  - **路由**只过 [MINI_PHONE]：模块打进包里、路由照旧注册，
 *    所以搜索命中与 deep link 仍能进入 —— 这是刻意的，不是漏藏。
 *
 * 为什么允许留路由：小手机不是"关掉的功能"，而是"已重写、暂不作主推入口"的功能；
 * 裁掉路由会让搜索命中的结果与恢复的导航栈指向不存在的页面，
 * 那比"能进但没入口"更难解释。要彻底不可达就把 [MINI_PHONE] 改回 false。
 */
object FeatureFlags {
    /**
     * 小手机（MiniPhone）完整功能。
     *
     * v2.6.6 关闭过一轮（当时 UI 与交互未定稿）；v2.6.12 起已重写为独立模块
     * （`:miniphone`，自带数据库与美术体系），重新对外开放。
     *
     * 2.6.24 / 2.6.25 两个正式包整体收起过（入口、路由、后台唤醒一并停），
     * 2.6.26 起随 R0–R10 重写完成重新放出。
     *
     * **2.6.27 再次整体收起**：入口、路由、后台唤醒全部停掉，界面上不出现任何小手机痕迹。
     * 代码一行未删，改回 true 即可恢复。
     *
     * **恢复前必须知道的一条**：v2.6.18–v2.6.22 三个已发布版本里这一项是 true，
     * 启动时会无条件注册每 3 小时唤醒的 Worker，而它会解析 Koin 并打开 `miniphone.db`（当时是 v5）。
     * 也就是说老用户设备上可能已经有一个 v5 库，升级上来要走 v5→v6→v7→v8 整条迁移链。
     * 迁移链有整链测试（`MiniPhoneDbMigrationChainTest`，逐段点名核对表），但那是 Robolectric 的 SQLite；
     * 真机库文件、备份恢复、以及「升级中途被杀」仍需真机自验。
     */
    const val MINI_PHONE: Boolean = false

    /**
     * 小手机是否在首页与设置分类页露出入口。
     *
     * 与本功能本身的存放分开：[MINI_PHONE] 控制模块与路由是否存在，
     * 这一项只控制“看不看得见”。
     *
     * 2.6.24 / 2.6.25 先不露入口；2.6.26 起随小手机一起打开；
     * **2.6.27 起再次关闭**（与 [MINI_PHONE] 同为 false）。
     */
    const val MINI_PHONE_ENTRY: Boolean = false

    /** 小手机内嵌的"AI 朋友圈"（Moments）。依赖 [MINI_PHONE]。 */
    const val MOMENTS: Boolean = MINI_PHONE
}
