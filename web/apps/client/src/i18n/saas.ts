export type SaasMessage = keyof typeof SAAS_ES;

export function translateSaas(
  source: SaasMessage,
  params?: TranslateParams,
  languages: readonly string[] = navigatorLanguages(),
): string {
  const locale = resolveLocale("system", languages);
  return formatMessage(locale === "es" ? SAAS_ES[source] : source, params);
}
